def create_readme(output_dir: str) -> None:
    """Create a placeholder README.md."""
    path = os.path.join(output_dir, "README.md")
    content = """# Paper Figures

Generated by `paper-figures` skill.

## Directory Structure

- `src/` — Python source code for each figure
- `export/` — Final outputs (PDF + SVG + PNG)

## Figures

| ID | Filename | Type | Caption |
|----|----------|------|---------|

*Run the skill to populate this table.*
"""
    with open(path, "w") as f:
        f.write(content)
    print(f"  Created: {path}")


def scan_project() -> dict:
    """Scan the current directory for data sources."""
    info = {
        "csv_files": [],
        "model_files": [],
        "log_files": [],
        "config_data": None,
    }

    for root, dirs, files in os.walk("."):
        # Skip hidden dirs and venv
        dirs[:] = [d for d in dirs if not d.startswith(".") and d != "__pycache__" and d != "venv" and d != ".venv"]

        for f in files:
            path = os.path.join(root, f)
            rel = os.path.relpath(path, ".")

            if f.endswith(".csv"):
                info["csv_files"].append(rel)
            elif f.endswith(".py"):
                try:
                    with open(rel) as fh:
                        content = fh.read()
                    if "nn.Module" in content or "class " in content:
                        info["model_files"].append(rel)
                except Exception:
                    pass
            elif f.endswith(".log") or "metrics" in f.lower():
                info["log_files"].append(rel)

    return info


def main():
    parser = argparse.ArgumentParser(description="Setup figure directory structure")
    parser.add_argument("--output-dir", default="figures", help="Output directory name")
    parser.add_argument("--journal", default="generic",
                        choices=["ieee", "nature", "elsevier", "acm", "generic"],
                        help="Target journal style")
    parser.add_argument("--scan-only", action="store_true", help="Only scan for data sources")
    args = parser.parse_args()

    if args.scan_only:
        info = scan_project()
        print(json.dumps(info, indent=2))
        return

    print("Setting up figure directories...")
    setup_figure_dirs(args.output_dir)

    print("\nCreating default style config...")
    create_default_style(args.output_dir, args.journal)

    print("\nCreating README...")
    create_readme(args.output_dir)

    print("\nScanning project for data sources...")
    info = scan_project()
    if info["csv_files"]:
        print(f"  CSV files found: {info['csv_files']}")
    if info["model_files"]:
        print(f"  Model files found: {info['model_files']}")
    if info["log_files"]:
        print(f"  Log files found: {info['log_files']}")

    print(f"\nDone! Figure directory ready at: {args.output_dir}/")
    print(f"  src/     — place generated Python code here")
    print(f"  export/  — final PDF/SVG/PNG outputs go here")


if __name__ == "__main__":
    main()
