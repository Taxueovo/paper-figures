#!/usr/bin/env python3
"""Initialize figure directory structure in the current project.

Usage:
    python setup_project.py [--output-dir figures]

Creates:
    figures/
        src/          # Python source code for each figure
        export/       # Final PDF + SVG + PNG outputs
        style_config.json
        figure_plan.json
        README.md
"""

import argparse
import json
import os
import sys


def setup_figure_dirs(output_dir: str = "figures") -> None:
    """Create the figure directory structure."""
    dirs = [
        output_dir,
        os.path.join(output_dir, "src"),
        os.path.join(output_dir, "export"),
    ]
    for d in dirs:
        os.makedirs(d, exist_ok=True)
        print(f"  Created: {d}/")


